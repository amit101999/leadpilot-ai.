import { AppError } from "./errors";

/**
 * Reads a request body as UTF-8 text, refusing it as soon as it exceeds `limit` bytes. The stream is cancelled
 * at that point, so an oversized or chunked upload (no Content-Length) is never buffered in full.
 */
export async function readLimitedText(
  body: ReadableStream<Uint8Array> | null,
  limit: number,
): Promise<string> {
  if (!body) return "";
  const reader = body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > limit) {
      await reader.cancel().catch(() => undefined);
      throw new AppError("VALIDATION_ERROR", "Request body too large");
    }
    chunks.push(value);
  }
  const bytes = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    bytes.set(chunk, offset);
    offset += chunk.byteLength;
  }
  return new TextDecoder().decode(bytes);
}
