#!/usr/bin/env node
/**
 * Claude Code Stop hook. After every Claude response, appends a factual entry
 * to docs/progress/activity-log.md in the MAIN checkout whenever the
 * repository state (HEAD or uncommitted files) changed since the last entry
 * for that checkout/worktree. No AI involved: it only records git facts, so
 * it is instant and free. The project-tracker subagent reads this log.
 *
 * Never fails the session: every error is swallowed and the hook exits 0.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const PROGRESS_DIR = "docs/progress";
const MAX_FILES_PER_COMMIT = 40;
const MAX_UNCOMMITTED = 60;

// trimEnd, not trim: `git status --porcelain` lines start with a meaningful space (" M file").
function git(cwd, args) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trimEnd();
}

function lines(text) {
  return text.split("\n").filter(Boolean);
}

function readHookInput() {
  try {
    return JSON.parse(readFileSync(0, "utf8") || "{}");
  } catch {
    return {};
  }
}

function readState(statePath) {
  try {
    return JSON.parse(readFileSync(statePath, "utf8"));
  } catch {
    return {};
  }
}

function commitDetails(top, from, to) {
  const range = from ? [`${from}..${to}`] : ["-1", to];
  return lines(git(top, ["log", "--reverse", "--format=%h%x09%s", ...range])).map((row) => {
    const [hash, subject] = row.split("\t");
    const files = lines(git(top, ["diff-tree", "--no-commit-id", "--name-status", "-r", "--root", hash]));
    return { hash, subject, files };
  });
}

function main() {
  const input = readHookInput();
  const cwd = input.cwd || process.env.CLAUDE_PROJECT_DIR || process.cwd();

  let top;
  let mainRoot;
  try {
    top = git(cwd, ["rev-parse", "--show-toplevel"]);
    // The common git dir is <main checkout>/.git for both the main checkout and its worktrees.
    mainRoot = path.dirname(path.resolve(top, git(top, ["rev-parse", "--git-common-dir"])));
  } catch {
    return; // not a git repository
  }

  let head;
  try {
    head = git(top, ["rev-parse", "HEAD"]);
  } catch {
    return; // no commits yet
  }

  const progressDir = path.join(mainRoot, PROGRESS_DIR);
  const statePath = path.join(progressDir, ".activity-state.json");
  const logPath = path.join(progressDir, "activity-log.md");

  const branch = git(top, ["branch", "--show-current"]) || "(detached HEAD)";
  // Ignore the tracker's own files so writing the log never counts as a change.
  const uncommitted = lines(git(top, ["status", "--porcelain", "--untracked-files=all"])).filter(
    (row) => !row.slice(3).startsWith(`${PROGRESS_DIR}/`),
  );

  const fingerprint = createHash("sha256")
    .update(`${head}\n${uncommitted.join("\n")}`)
    .digest("hex");
  const state = readState(statePath);
  const previous = state[top];
  if (previous && previous.fingerprint === fingerprint) return;

  let commits = [];
  if (!previous || previous.head !== head) {
    try {
      commits = commitDetails(top, previous?.head, head);
    } catch {
      commits = commitDetails(top, null, head); // previous head no longer reachable (rebase/reset)
    }
  }

  const location = path.relative(mainRoot, top).replaceAll("\\", "/") || "main checkout";
  const out = [`## ${new Date().toISOString()} | ${branch} | ${location}`, ""];
  out.push(`HEAD: \`${head.slice(0, 7)}\``);
  if (input.session_id) out.push(`Session: \`${input.session_id}\``);
  if (commits.length > 0) {
    out.push("", previous ? "New commits:" : "Current commit (first entry for this checkout):");
    for (const commit of commits) {
      out.push(`- \`${commit.hash}\` ${commit.subject}`);
      for (const file of commit.files.slice(0, MAX_FILES_PER_COMMIT))
        out.push(`  - ${file.replace("\t", " ")}`);
      if (commit.files.length > MAX_FILES_PER_COMMIT) {
        out.push(`  - ...and ${commit.files.length - MAX_FILES_PER_COMMIT} more files`);
      }
    }
  }
  out.push("", uncommitted.length > 0 ? "Uncommitted changes:" : "Working tree clean.");
  for (const row of uncommitted.slice(0, MAX_UNCOMMITTED))
    out.push(`- \`${row.slice(0, 2)}\` ${row.slice(3)}`);
  if (uncommitted.length > MAX_UNCOMMITTED) out.push(`- ...and ${uncommitted.length - MAX_UNCOMMITTED} more`);
  out.push("", "");

  mkdirSync(progressDir, { recursive: true });
  if (!existsSync(logPath)) {
    writeFileSync(
      logPath,
      "# Activity log\n\nAuto-generated by `scripts/progress/record-activity.mjs` (Claude Code Stop hook).\n" +
        "One entry per Claude response that changed the repository. Facts from git only.\n\n",
    );
  }
  appendFileSync(logPath, out.join("\n"));
  state[top] = { head, fingerprint, recordedAt: new Date().toISOString() };
  writeFileSync(statePath, `${JSON.stringify(state, null, 2)}\n`);
}

try {
  main();
} catch {
  // A tracking failure must never interrupt the Claude session.
}
